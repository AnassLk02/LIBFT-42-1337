#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	size_t	bytes;
	size_t	total;
	void	*ptr;

	bytes = 0;
	total = nmemb * size;
	if (nmemb != 0 && total / nmemb != size)
		return (NULL);
	ptr = malloc(total);
	if (!ptr)
		return (NULL);
	while (bytes < total)
	{
		((char *)ptr)[bytes] = 0;
		bytes++;
	}
	return (ptr);
}
